using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Vlingo.Xoom.Actors.Toolbox.Generator
{
    /// <summary>
    /// Writes the <c>&lt;Protocol&gt;__Proxy</c> class of every <c>[ActorProtocol]</c> interface while
    /// the project is compiled.
    ///
    /// This is all the runtime needs: <c>ActorProxy.CreateFor</c> looks the proxy class up by name and
    /// only compiles one with Roslyn when it is not found. Generating it at build time therefore
    /// removes the runtime compilation of the proxy, keeps builds reproducible, and is what makes
    /// trimming and native ahead-of-time compilation possible.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class ProtocolProxyGenerator : IIncrementalGenerator
    {
        private const string ProtocolAttribute = "Vlingo.Xoom.Actors.Toolbox.ActorProtocolAttribute";
        private const string ProxySuffix = "__Proxy";
        private const string IProxy = "global::Vlingo.Xoom.Actors.IProxy";
        private const string Actor = "global::Vlingo.Xoom.Actors.Actor";
        private const string IMailbox = "global::Vlingo.Xoom.Actors.IMailbox";
        private const string IAddress = "global::Vlingo.Xoom.Actors.IAddress";
        private const string DeadLetter = "global::Vlingo.Xoom.Actors.DeadLetter";
        private const string LocalMessage = "global::Vlingo.Xoom.Actors.LocalMessage";
        private const string ExecutorDispatcherAsync = "global::Vlingo.Xoom.Actors.ExecutorDispatcherAsync";
        private const string BasicCompletes = "global::Vlingo.Xoom.Common.BasicCompletes";
        private const string ICompletesName = "ICompletes";
        private const string TaskName = "Task";
        private const string TasksNamespace = "System.Threading.Tasks";

        private static readonly SymbolDisplayFormat Code = SymbolDisplayFormat.FullyQualifiedFormat;

        private static readonly SymbolDisplayFormat Name = SymbolDisplayFormat.FullyQualifiedFormat
            .WithGlobalNamespaceStyle(SymbolDisplayGlobalNamespaceStyle.Omitted);

        private static readonly string[] ReservedKeywords =
        {
            "object", "event", "struct", "class", "const", "delegate", "interface", "protected",
            "static", "sealed", "string", "double", "checked"
        };

        private static readonly DiagnosticDescriptor NestedProtocol = new DiagnosticDescriptor(
            "XOOM001",
            "Nested protocol",
            "The toolbox does not generate a proxy for the nested protocol '{0}' yet; xoom-actors "
                + "generates it while the application runs",
            "Vlingo.Xoom.Actors.Toolbox",
            DiagnosticSeverity.Warning,
            true);

        /// <inheritdoc/>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var protocols = context.SyntaxProvider.ForAttributeWithMetadataName(
                ProtocolAttribute,
                (node, _) => node is InterfaceDeclarationSyntax,
                (context, _) => (INamedTypeSymbol)context.TargetSymbol);

            context.RegisterSourceOutput(protocols, Emit);
        }

        private static void Emit(SourceProductionContext output, INamedTypeSymbol protocol)
        {
            if (protocol.ContainingType != null)
            {
                output.ReportDiagnostic(Diagnostic.Create(
                    NestedProtocol, protocol.Locations.FirstOrDefault(), protocol.Name));
                return;
            }

            output.AddSource(
                ProxyClassNameOf(protocol) + ".g.cs",
                SourceText.From(Source(protocol), Encoding.UTF8));
        }

        private static string Source(INamedTypeSymbol protocol)
        {
            var protocolType = protocol.ToDisplayString(Code);
            var protocolName = protocol.ToDisplayString(Name);
            var members = ProxyMembers(protocol).ToList();
            var source = new StringBuilder();

            source.AppendLine("// <auto-generated/>");
            source.AppendLine("#nullable enable");
            source.AppendLine();
            source.AppendLine("using System;");
            source.AppendLine("using System.Threading.Tasks;");
            source.AppendLine();

            if (!protocol.ContainingNamespace.IsGlobalNamespace)
            {
                source.Append("namespace ").Append(protocol.ContainingNamespace.ToDisplayString()).AppendLine(";");
                source.AppendLine();
            }

            source.Append("public class ").Append(ProxyClassNameOf(protocol)).Append(TypeParametersOf(protocol.TypeParameters))
                .Append(" : ").Append(IProxy).Append(", ").Append(protocolName)
                .Append(ConstraintsOf(protocol.TypeParameters)).AppendLine();
            source.AppendLine("{");
            AppendRepresentations(source, members);
            AppendFields(source);
            AppendConstructor(source, ProxyClassNameOf(protocol));
            AppendObjectMembers(source, protocolName);
            for (var index = 0; index < members.Count; index++)
            {
                AppendMember(source, protocolType, members[index], index + 1);
            }
            source.AppendLine("}");

            return source.ToString();
        }

        private static void AppendRepresentations(StringBuilder source, List<ISymbol> members)
        {
            for (var index = 0; index < members.Count; index++)
            {
                var member = members[index];
                if (member is IMethodSymbol method)
                {
                    source.Append("    private const string ").Append(RepresentationNameOf(method, index + 1))
                        .Append(" = \"").Append(MethodNameOf(method)).Append('(')
                        .Append(string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(Name))))
                        .AppendLine(")\";");
                }
            }

            source.AppendLine();
        }

        private static void AppendFields(StringBuilder source)
        {
            source.Append("    private readonly ").Append(Actor).AppendLine(" actor;");
            source.Append("    private readonly ").Append(IMailbox).AppendLine(" mailbox;");
            source.AppendLine();
        }

        private static void AppendConstructor(StringBuilder source, string proxyClassName)
        {
            source.Append("    public ").Append(proxyClassName).Append('(').Append(Actor)
                .Append(" actor, ").Append(IMailbox).AppendLine(" mailbox)");
            source.AppendLine("    {");
            source.AppendLine("        this.actor = actor;");
            source.AppendLine("        this.mailbox = mailbox;");
            source.AppendLine("    }");
            source.AppendLine();
        }

        private static void AppendObjectMembers(StringBuilder source, string protocolName)
        {
            source.Append("    public ").Append(IAddress).AppendLine(" Address => this.actor.Address;");
            source.AppendLine();
            source.AppendLine("    public override bool Equals(object? other)");
            source.AppendLine("    {");
            source.AppendLine("        if (this == other) return true;");
            source.AppendLine("        if (other == null) return false;");
            source.AppendLine("        if (other.GetType() != GetType()) return false;");
            const string otherAddress = "((" + IProxy + ")other).Address";
            source.Append("        return this.actor.Address.Equals(").Append(otherAddress).AppendLine(");");
            source.AppendLine("    }");
            source.AppendLine();
            source.AppendLine("    public override int GetHashCode() => 31 + GetType().GetHashCode() + this.actor.Address.GetHashCode();");
            source.AppendLine();
            source.Append("    public override string ToString() => \"").Append(protocolName)
                .AppendLine("[Address=\" + this.actor.Address + \"]\";");
            source.AppendLine();
        }

        private static void AppendMember(StringBuilder source, string protocolType, ISymbol member, int index)
        {
            if (member is IMethodSymbol method)
            {
                AppendMethod(source, protocolType, method, index);
            }
            else if (member is IPropertySymbol property)
            {
                AppendProperty(source, property);
            }
        }

        private static void AppendMethod(StringBuilder source, string protocolType, IMethodSymbol method, int index)
        {
            var representation = RepresentationNameOf(method, index);
            var result = ResultOf(method.ReturnType);
            var call = "__." + MethodNameOf(method) + "(" + ArgumentsOf(method) + ")";

            source.Append("    public ").Append(method.ReturnType.ToDisplayString(Code)).Append(' ')
                .Append(MethodNameOf(method)).Append('(').Append(ParametersOf(method)).Append(')')
                .Append(ConstraintsOf(method.TypeParameters)).AppendLine();
            source.AppendLine("    {");
            source.AppendLine("        if (!this.actor.IsStopped)");
            source.AppendLine("        {");

            var consumer = "consumer";
            if (result == Result.Task)
            {
                consumer = "asyncWrapper";
                var task = (INamedTypeSymbol)method.ReturnType;
                var resultType = task.TypeArguments.Length > 0 ? task.TypeArguments[0].ToDisplayString(Code) : "object";
                source.Append("            var tcs = new TaskCompletionSource<Task<").Append(resultType).AppendLine(">>();");
                source.Append("            Func<").Append(protocolType).Append(", Task<").Append(resultType)
                    .Append(">> consumer = __ =>").AppendLine();
                source.AppendLine("            {");
                source.Append("                tcs.SetResult(").Append(call).AppendLine(");");
                source.AppendLine("                return tcs.Task.Unwrap();");
                source.AppendLine("            };");
                source.Append("            Action<").Append(protocolType).AppendLine("> asyncWrapper = m =>");
                source.AppendLine("            {");
                source.AppendLine("                Task Wrap() => consumer(m);");
                source.Append("                ").Append(ExecutorDispatcherAsync).Append(".RunTask<").Append(protocolType)
                    .AppendLine(">(Wrap, this.mailbox, this.actor);");
                source.AppendLine("            };");
            }
            else
            {
                source.Append("            Action<").Append(protocolType).Append("> consumer = __ => ").Append(call).AppendLine(";");
            }

            if (result == Result.Completes)
            {
                source.Append("            var completes = new ").Append(BasicCompletes).Append('<')
                    .Append(CompletedTypeOf(method.ReturnType)).AppendLine(">(this.actor.Scheduler);");
            }

            source.AppendLine("            if (this.mailbox.IsPreallocated)");
            source.AppendLine("            {");
            source.Append("                this.mailbox.Send(this.actor, ").Append(consumer).Append(", ")
                .Append(result == Result.Completes ? "completes" : "null").Append(", ").Append(representation).AppendLine(");");
            source.AppendLine("            }");
            source.AppendLine("            else");
            source.AppendLine("            {");
            source.Append("                this.mailbox.Send(new ").Append(LocalMessage).Append('<').Append(protocolType)
                .Append(">(this.actor, ").Append(consumer).Append(", ")
                .Append(result == Result.Completes ? "completes, " : string.Empty).Append(representation).AppendLine("));");
            source.AppendLine("            }");
            source.AppendLine();

            if (result == Result.Completes)
            {
                source.AppendLine("            return completes;");
            }
            else if (result == Result.Task)
            {
                source.AppendLine("            return tcs.Task.Unwrap();");
            }

            source.AppendLine("        }");
            source.AppendLine();
            source.Append("        this.actor.DeadLetters?.FailedDelivery(new ").Append(DeadLetter)
                .Append("(this.actor, ").Append(representation).AppendLine("));");

            if (!method.ReturnsVoid)
            {
                source.AppendLine("        return default!;");
            }

            source.AppendLine("    }");
            source.AppendLine();
        }

        private static void AppendProperty(StringBuilder source, IPropertySymbol property)
        {
            source.Append("    public ").Append(property.Type.ToDisplayString(Code)).Append(' ')
                .Append(KeywordOf(property.Name));
            source.AppendLine(property.SetMethod != null ? " { get; set; }" : " => default!;");
            source.AppendLine();
        }

        private static string ArgumentsOf(IMethodSymbol method) =>
            string.Join(", ", method.Parameters.Select(p => KeywordOf(p.Name)));

        private static string ParametersOf(IMethodSymbol method) =>
            string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(Code) + " " + KeywordOf(p.Name)));

        private static string MethodNameOf(IMethodSymbol method) =>
            method.IsGenericMethod
                ? method.Name + "<" + string.Join(", ", method.TypeParameters.Select(p => p.Name)) + ">"
                : method.Name;

        private static string RepresentationNameOf(IMethodSymbol method, int index) =>
            method.Name + "Representation" + index;

        private static string CompletedTypeOf(ITypeSymbol returnType) =>
            returnType is INamedTypeSymbol named && named.TypeArguments.Length > 0
                ? named.TypeArguments[0].ToDisplayString(Code)
                : "object";

        private static string TypeParametersOf(IEnumerable<ITypeParameterSymbol> parameters)
        {
            var names = parameters.Select(p => p.Name).ToList();
            return names.Count == 0 ? string.Empty : "<" + string.Join(", ", names) + ">";
        }

        private static string ConstraintsOf(IEnumerable<ITypeParameterSymbol> parameters)
        {
            var constraints = new List<string>();
            foreach (var parameter in parameters)
            {
                var kinds = new List<string>();
                if (parameter.HasUnmanagedTypeConstraint)
                {
                    kinds.Add("unmanaged");
                }
                else if (parameter.HasValueTypeConstraint)
                {
                    kinds.Add("struct");
                }
                else if (parameter.HasReferenceTypeConstraint)
                {
                    kinds.Add("class");
                }

                if (parameter.HasNotNullConstraint)
                {
                    kinds.Add("notnull");
                }

                kinds.AddRange(parameter.ConstraintTypes.Select(c => c.ToDisplayString(Code)));

                if (parameter.HasConstructorConstraint && !parameter.HasValueTypeConstraint && !parameter.HasUnmanagedTypeConstraint)
                {
                    kinds.Add("new()");
                }

                if (kinds.Count > 0)
                {
                    constraints.Add("where " + parameter.Name + " : " + string.Join(", ", kinds));
                }
            }

            return constraints.Count == 0 ? string.Empty : " " + string.Join(" ", constraints);
        }

        private static string KeywordOf(string name) =>
            ReservedKeywords.Contains(name) ? "@" + name : name;

        private static Result ResultOf(ITypeSymbol returnType)
        {
            if (IsTask(returnType))
            {
                return Result.Task;
            }

            return IsCompletes(returnType) ? Result.Completes : Result.Plain;
        }

        private static bool IsTask(ITypeSymbol type) =>
            type.Name == TaskName && type.ContainingNamespace.ToDisplayString() == TasksNamespace;

        private static bool IsCompletes(ITypeSymbol type) =>
            type.Name == ICompletesName || type.AllInterfaces.Any(i => i.Name == ICompletesName);

        private static List<ISymbol> ProxyMembers(INamedTypeSymbol protocol)
        {
            var members = new List<ISymbol>();
            var seen = new HashSet<string>();
            var types = new List<INamedTypeSymbol> { protocol };
            types.AddRange(protocol.AllInterfaces);

            foreach (var type in types)
            {
                foreach (var member in type.GetMembers())
                {
                    if (member.IsStatic)
                    {
                        continue;
                    }

                    if (member is IMethodSymbol method && (method.MethodKind != MethodKind.Ordinary || !method.IsAbstract))
                    {
                        continue;
                    }

                    if (!(member is IMethodSymbol) && !(member is IPropertySymbol))
                    {
                        continue;
                    }

                    if (seen.Add(KeyOf(member)))
                    {
                        members.Add(member);
                    }
                }
            }

            return members;
        }

        private static string KeyOf(ISymbol member) =>
            member is IMethodSymbol method
                ? method.Name + "(" + string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(Name))) + ")"
                : member.Name;

        /// <summary>
        /// Answers the name the runtime composes, which is the protocol's name without the
        /// C#-style <c>I</c> interface prefix, followed by <c>__Proxy</c>.
        /// </summary>
        private static string ProxyClassNameOf(INamedTypeSymbol protocol) =>
            ProtocolNameOf(protocol.Name) + ProxySuffix;

        private static string ProtocolNameOf(string name) =>
            name.Length > 1 && name[0] == 'I' && char.IsUpper(name[1]) ? name.Substring(1) : name;

        private enum Result
        {
            Plain,
            Completes,
            Task
        }
    }
}
